UPGRADE = f"""
-- ------------------------------------------------------------------ identity and access
CREATE TABLE users (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email             TEXT NOT NULL,
    username          TEXT,
    name              TEXT NOT NULL DEFAULT '',
    password_hash     TEXT NOT NULL,
    is_active         BOOLEAN NOT NULL DEFAULT TRUE,
    email_verified_at TIMESTAMPTZ,
    failed_logins     INTEGER NOT NULL DEFAULT 0,
    locked_until      TIMESTAMPTZ,
    last_login_at     TIMESTAMPTZ,
    created_at        TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX ux_users_email ON users (lower(email));
CREATE UNIQUE INDEX ux_users_username ON users (lower(username)) WHERE username IS NOT NULL;

CREATE TABLE workspaces (
    id         {ID},
    name       TEXT NOT NULL,
    created_by BIGINT REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE workspace_members (
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role         TEXT NOT NULL CHECK (role IN ('admin', 'write', 'read')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (workspace_id, user_id)
);
CREATE INDEX ix_members_user ON workspace_members (user_id);

CREATE TABLE email_verifications (
    id          {ID},
    user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    code_hash   TEXT NOT NULL,
    attempts    INTEGER NOT NULL DEFAULT 0,
    expires_at  TIMESTAMPTZ NOT NULL,
    consumed_at TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX ix_verifications_user ON email_verifications (user_id);

CREATE TABLE sessions (
    id           TEXT PRIMARY KEY,                -- sha256 of the cookie token
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    workspace_id BIGINT REFERENCES workspaces(id) ON DELETE SET NULL,
    csrf_token   TEXT NOT NULL,
    ip           TEXT NOT NULL DEFAULT '',
    user_agent   TEXT NOT NULL DEFAULT '',
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    expires_at   TIMESTAMPTZ NOT NULL
);
CREATE INDEX ix_sessions_user ON sessions (user_id);

CREATE TABLE api_keys (
    id           {ID},
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    user_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    name         TEXT NOT NULL,
    prefix       TEXT NOT NULL UNIQUE,
    key_hash     TEXT NOT NULL,                   -- argon2id of the full key
    role         TEXT NOT NULL CHECK (role IN ('admin', 'write', 'read')),
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ,
    expires_at   TIMESTAMPTZ,
    revoked_at   TIMESTAMPTZ
);
CREATE INDEX ix_api_keys_workspace ON api_keys (workspace_id);

CREATE TABLE workspace_settings (
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    key          TEXT NOT NULL,
    value        TEXT NOT NULL,                   -- secrets are Fernet-encrypted
    PRIMARY KEY (workspace_id, key)
);

-- ------------------------------------------------------------------ reviews and threat models
CREATE TABLE reviews (
    id                  {ID},
    workspace_id        BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    kind                TEXT NOT NULL DEFAULT 'review',        -- review | threat_model
    title               TEXT NOT NULL,
    description         TEXT NOT NULL DEFAULT '',
    change_type         TEXT NOT NULL DEFAULT 'new',
    requester           TEXT NOT NULL DEFAULT '',
    business_owner      TEXT NOT NULL DEFAULT '',
    reviewer            TEXT NOT NULL DEFAULT '',
    business_unit       TEXT NOT NULL DEFAULT '',
    data_classification TEXT NOT NULL DEFAULT 'internal',
    tech_stack          TEXT NOT NULL DEFAULT '',
    internet_facing     INTEGER NOT NULL DEFAULT 0,
    personal_data       INTEGER NOT NULL DEFAULT 0,
    third_party         INTEGER NOT NULL DEFAULT 0,
    uses_ai             INTEGER NOT NULL DEFAULT 0,
    status              TEXT NOT NULL DEFAULT 'new',
    priority            TEXT NOT NULL DEFAULT 'medium',
    risk_rating         TEXT NOT NULL DEFAULT '',
    due_date            TEXT NOT NULL DEFAULT '',
    technologies        TEXT NOT NULL DEFAULT '[]',
    services            TEXT NOT NULL DEFAULT '[]',
    ai_meta             TEXT NOT NULL DEFAULT '{{}}',
    decision_notes      TEXT NOT NULL DEFAULT '',
    exposure            TEXT NOT NULL DEFAULT 'internal',      -- internal | partner | public
    data_types          TEXT NOT NULL DEFAULT '[]',
    interacts_with      TEXT NOT NULL DEFAULT '[]',
    system_types        TEXT NOT NULL DEFAULT '[]',
    design              TEXT NOT NULL DEFAULT '{{}}',
    code_review         TEXT NOT NULL DEFAULT '{{}}',
    created_at          TEXT NOT NULL,
    updated_at          TEXT NOT NULL
);
CREATE INDEX ix_reviews_workspace ON reviews (workspace_id, kind);

CREATE TABLE items (
    id                 {ID},
    review_id          BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    kind               TEXT NOT NULL DEFAULT 'question',
    subcategory_id     TEXT,
    library_ref        TEXT NOT NULL DEFAULT '',
    title              TEXT NOT NULL DEFAULT '',
    answer             TEXT NOT NULL DEFAULT '',
    notes              TEXT NOT NULL DEFAULT '',
    status             TEXT NOT NULL DEFAULT 'open',
    priority           TEXT NOT NULL DEFAULT 'medium',
    rationale          TEXT NOT NULL DEFAULT '',
    source             TEXT NOT NULL DEFAULT 'manual',
    is_risk            INTEGER NOT NULL DEFAULT 0,
    is_recommendation  INTEGER NOT NULL DEFAULT 0,
    risk               TEXT NOT NULL DEFAULT '',
    likelihood         TEXT NOT NULL DEFAULT '',
    impact             TEXT NOT NULL DEFAULT '',
    impact_description TEXT NOT NULL DEFAULT '',
    treatment          TEXT NOT NULL DEFAULT '',
    recommendation     TEXT NOT NULL DEFAULT '',
    rec_status         TEXT NOT NULL DEFAULT '',
    created_at         TEXT NOT NULL,
    updated_at         TEXT NOT NULL
);
CREATE UNIQUE INDEX ux_items_csf ON items (review_id, subcategory_id) WHERE subcategory_id IS NOT NULL;
CREATE INDEX ix_items_review ON items (review_id);

CREATE TABLE mitigations (
    id          {ID},
    review_id   BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    title       TEXT NOT NULL,
    description TEXT NOT NULL DEFAULT '',
    state       TEXT NOT NULL DEFAULT 'new',
    status      TEXT NOT NULL DEFAULT 'proposed',
    owner       TEXT NOT NULL DEFAULT '',
    due_date    TEXT NOT NULL DEFAULT '',
    nist        TEXT NOT NULL DEFAULT '[]',
    library_ref TEXT NOT NULL DEFAULT '',
    source      TEXT NOT NULL DEFAULT 'manual',
    created_at  TEXT NOT NULL,
    updated_at  TEXT NOT NULL
);
CREATE INDEX ix_mit_review ON mitigations (review_id);

CREATE TABLE item_mitigations (
    item_id       BIGINT NOT NULL REFERENCES items(id) ON DELETE CASCADE,
    mitigation_id BIGINT NOT NULL REFERENCES mitigations(id) ON DELETE CASCADE,
    PRIMARY KEY (item_id, mitigation_id)
);
CREATE INDEX ix_item_mit_mitigation ON item_mitigations (mitigation_id);

CREATE TABLE documents (
    id         {ID},
    review_id  BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL,
    filename   TEXT NOT NULL,
    mime       TEXT NOT NULL DEFAULT '',
    size       BIGINT NOT NULL DEFAULT 0,
    sha256     TEXT NOT NULL DEFAULT '',
    path       TEXT NOT NULL,
    meta       TEXT NOT NULL DEFAULT '{{}}',
    created_at TEXT NOT NULL
);
CREATE INDEX ix_documents_review ON documents (review_id);

CREATE TABLE review_checks (
    review_id  BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    check_id   TEXT NOT NULL,
    status     TEXT NOT NULL DEFAULT 'applicable',
    note       TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL,
    PRIMARY KEY (review_id, check_id)
);

CREATE TABLE activity (
    id        {ID},
    review_id BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    ts        TEXT NOT NULL,
    action    TEXT NOT NULL,
    detail    TEXT NOT NULL DEFAULT ''
);
CREATE INDEX ix_activity_review ON activity (review_id);

CREATE TABLE jobs (
    id           {ID},
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    review_id    BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    kind         TEXT NOT NULL,
    status       TEXT NOT NULL DEFAULT 'queued',   -- queued | running | done | error
    progress     DOUBLE PRECISION NOT NULL DEFAULT 0,
    message      TEXT NOT NULL DEFAULT '',
    result       TEXT NOT NULL DEFAULT '{{}}',
    error        TEXT NOT NULL DEFAULT '',
    created_at   TEXT NOT NULL,
    updated_at   TEXT NOT NULL
);
CREATE INDEX ix_jobs_review ON jobs (review_id, status);

-- Deterministic AI: identical prompt + inputs => identical stored answer (per workspace).
CREATE TABLE ai_cache (
    workspace_id BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    key          TEXT NOT NULL,
    provider     TEXT NOT NULL,
    value        TEXT NOT NULL,
    created_at   TEXT NOT NULL,
    PRIMARY KEY (workspace_id, key)
);

-- Reviewer-managed requirement <-> Checkov check links; review_id NULL = all reviews of the workspace.
CREATE TABLE check_links (
    id             {ID},
    workspace_id   BIGINT NOT NULL REFERENCES workspaces(id) ON DELETE CASCADE,
    requirement_id TEXT NOT NULL,
    check_id       TEXT NOT NULL,
    action         TEXT NOT NULL CHECK (action IN ('include', 'exclude')),
    review_id      BIGINT REFERENCES reviews(id) ON DELETE CASCADE,
    note           TEXT NOT NULL DEFAULT '',
    created_at     TEXT NOT NULL,
    updated_at     TEXT NOT NULL,
    UNIQUE (requirement_id, check_id, review_id)
);
CREATE UNIQUE INDEX ux_check_links_global ON check_links (workspace_id, requirement_id, check_id)
    WHERE review_id IS NULL;
CREATE INDEX ix_check_links_req ON check_links (workspace_id, requirement_id);
CREATE INDEX ix_check_links_review ON check_links (review_id);

CREATE TABLE review_threat_models (
    review_id       BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    threat_model_id BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    links           TEXT NOT NULL DEFAULT '{{}}',
    linked_at       TEXT NOT NULL,
    PRIMARY KEY (review_id, threat_model_id)
);
CREATE INDEX ix_rtm_threat_model ON review_threat_models (threat_model_id);

CREATE TABLE threat_artifacts (
    review_id  BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    kind       TEXT NOT NULL,
    data       TEXT NOT NULL DEFAULT '{{}}',
    source     TEXT NOT NULL DEFAULT 'ai',
    model      TEXT NOT NULL DEFAULT '',
    updated_at TEXT NOT NULL,
    PRIMARY KEY (review_id, kind)
);

CREATE TABLE code_fixes (
    review_id     BIGINT NOT NULL REFERENCES reviews(id) ON DELETE CASCADE,
    finding_id    TEXT NOT NULL,
    status        TEXT NOT NULL DEFAULT 'ready',
    patch         TEXT NOT NULL DEFAULT '',
    files         TEXT NOT NULL DEFAULT '[]',
    test_filename TEXT NOT NULL DEFAULT '',
    test_code     TEXT NOT NULL DEFAULT '',
    explanation   TEXT NOT NULL DEFAULT '',
    provider      TEXT NOT NULL DEFAULT '',
    error         TEXT NOT NULL DEFAULT '',
    created_at    TEXT NOT NULL,
    updated_at    TEXT NOT NULL,
    PRIMARY KEY (review_id, finding_id)
);
"""

